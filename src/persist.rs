//! `stance persist`: writes the current monitor setup to a file the user
//! loads once from their Hyprland config. The main config is never touched.

use std::path::PathBuf;

use crate::error::{Error, Result};
use crate::model::{Monitor, Parser};
use crate::spec::MonitorSpec;
use crate::store;

pub const NAME: &str = "stance-monitors";

pub fn path(parser: Parser) -> Result<PathBuf> {
    let ext = match parser {
        Parser::Lua => "lua",
        Parser::Legacy => "conf",
    };
    Ok(store::hypr_config_dir()?.join(format!("{NAME}.{ext}")))
}

/// The line the user adds to their config once.
pub fn load_line(parser: Parser) -> String {
    match parser {
        Parser::Lua => format!("require(\"{NAME}\")"),
        Parser::Legacy => format!("source = ~/.config/hypr/{NAME}.conf"),
    }
}

pub fn render(mons: &[Monitor], parser: Parser) -> Result<String> {
    let (c, mut out) = match parser {
        Parser::Lua => ("--", String::new()),
        Parser::Legacy => ("#", String::new()),
    };
    out.push_str(&format!(
        "{c} Generated by stance. Do not edit by hand; run `stance persist` again.\n{c} Load it once from your config with: {}\n\n",
        load_line(parser)
    ));
    // Sources before mirrors so the mirror target exists when the file loads.
    let mut specs: Vec<MonitorSpec> = mons.iter().map(MonitorSpec::from_monitor).collect();
    specs.sort_by_key(|s| s.mirror.is_some());
    for s in &specs {
        let desc = mons
            .iter()
            .find(|m| m.name == s.name)
            .map(|m| m.description.replace(['\n', '\r'], " "))
            .unwrap_or_default();
        out.push_str(&format!("{c} {desc}\n"));
        match parser {
            Parser::Lua => out.push_str(&s.to_lua()?),
            Parser::Legacy => {
                out.push_str("monitor = ");
                out.push_str(&s.to_legacy()?);
            }
        }
        out.push('\n');
    }
    Ok(out)
}

pub fn write(text: &str, parser: Parser) -> Result<PathBuf> {
    let p = path(parser)?;
    let dir = p.parent().ok_or_else(|| Error::new("io", "bad path"))?;
    if !dir.is_dir() {
        return Err(Error::new(
            "io",
            format!("{} does not exist", dir.display()),
        ));
    }
    store::atomic_write(&p, text.as_bytes(), true)?;
    Ok(p)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::apply::tests::mon;

    #[test]
    fn renders_both_parsers() {
        let mut b = mon("B-1", 0);
        b.mirror_of = Some("A-1".into());
        let mut c = mon("C-1", 0);
        c.enabled = false;
        c.description = "evil\n})os.execute('x')--".into();
        let mons = vec![b, mon("A-1", 0), c];
        let lua = render(&mons, Parser::Lua).unwrap();
        let a_at = lua.find("output = \"A-1\"").unwrap();
        let b_at = lua.find("output = \"B-1\"").unwrap();
        assert!(a_at < b_at, "mirror source first");
        assert!(lua.contains("mirror = \"A-1\""));
        assert!(lua.contains("hl.monitor({ output = \"C-1\", disabled = true })"));
        // Description stays inside a single comment line.
        assert!(lua.lines().all(|l| !l.starts_with("})os")));
        let conf = render(&mons, Parser::Legacy).unwrap();
        assert!(conf.contains("monitor = C-1,disable"));
        assert!(conf.contains("monitor = B-1,1920x1080@60,0x0,1,transform,0,vrr,0,mirror,A-1"));
    }
}
